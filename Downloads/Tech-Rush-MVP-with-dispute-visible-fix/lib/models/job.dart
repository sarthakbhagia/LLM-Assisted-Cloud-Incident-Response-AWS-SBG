class Job {
  final String id;
  final String? employerId;
  final String title;
  final String category;
  final String description;
  final double wage;
  final double? originalWage;
  final String status; // 'open', 'assigned', 'completed'
  final double rating;
  final int reviewCount;
  final String location;
  final String date;
  final String employerName;
  final String? workerName;
  final String? imageUrl;
  final bool verified;
  final bool urgent;

  const Job({
    required this.id,
    this.employerId,
    required this.title,
    required this.category,
    required this.description,
    required this.wage,
    this.originalWage,
    required this.status,
    required this.rating,
    required this.reviewCount,
    required this.location,
    required this.date,
    required this.employerName,
    this.workerName,
    this.imageUrl,
    this.verified = true,
    this.urgent = false,
  });

  factory Job.fromJson(Map<String, dynamic> json) {
    return Job(
      id: json['id']?.toString() ?? '',
      employerId: json['employer_id']?.toString(),
      title: json['title'] ?? '',
      category: json['category'] ?? 'General',
      description: json['description'] ?? '',
      wage: (json['price'] as num?)?.toDouble() ?? 0.0,
      originalWage: (json['original_price'] as num?)?.toDouble(),
      status: json['status'] ?? 'open',
      rating: (json['rating'] as num?)?.toDouble() ?? 5.0,
      reviewCount: (json['review_count'] as num?)?.toInt() ?? 0,
      location: json['location'] ?? 'Indiranagar',
      date: json['date'] ?? 'Today',
      employerName: json['employer_name'] ?? 'Employer',
      workerName: json['worker_name'],
      imageUrl: json['image_url'],
      verified: json['verified'] ?? true,
      urgent: json['urgent'] ?? false,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      if (id.isNotEmpty && !id.startsWith('job-')) 'id': id,
      if (employerId != null) 'employer_id': employerId,
      'title': title,
      'category': category,
      'description': description,
      'price': wage,
      if (originalWage != null) 'original_price': originalWage,
      'status': status,
      'rating': rating,
      'review_count': reviewCount,
      'location': location,
      'employer_name': employerName,
      if (workerName != null) 'worker_name': workerName,
      if (imageUrl != null) 'image_url': imageUrl,
      'verified': verified,
      'urgent': urgent,
    };
  }

  Job copyWith({
    String? id,
    String? employerId,
    String? title,
    String? category,
    String? description,
    double? wage,
    double? originalWage,
    String? status,
    double? rating,
    int? reviewCount,
    String? location,
    String? date,
    String? employerName,
    String? workerName,
    String? imageUrl,
    bool? verified,
    bool? urgent,
  }) {
    return Job(
      id: id ?? this.id,
      employerId: employerId ?? this.employerId,
      title: title ?? this.title,
      category: category ?? this.category,
      description: description ?? this.description,
      wage: wage ?? this.wage,
      originalWage: originalWage ?? this.originalWage,
      status: status ?? this.status,
      rating: rating ?? this.rating,
      reviewCount: reviewCount ?? this.reviewCount,
      location: location ?? this.location,
      date: date ?? this.date,
      employerName: employerName ?? this.employerName,
      workerName: workerName ?? this.workerName,
      imageUrl: imageUrl ?? this.imageUrl,
      verified: verified ?? this.verified,
      urgent: urgent ?? this.urgent,
    );
  }
}

